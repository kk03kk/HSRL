#!/usr/bin/env python3
"""Combine raw model-EOT source libraries into a late-weighted league library.

Sources are generated by ``build_v1_1_panel.py``; this script never rescales
boards or uses P50/Firestone calibration. Train is turn-weighted across sources;
dev/test are held-out game seeds and are not reused for training.
"""
from __future__ import annotations

import argparse
import gzip
import json
import random
import sys
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from hsbg.az.train.mirror_snapshots import (  # noqa: E402
    MirrorSnapshotPool, engine_stamp, write_snapshot_file,
)
from hsbg.az.train.personal import fingerprint, library_digest, sha256, write_json  # noqa: E402


SOURCES = [
    ("v1.1", Path("artifacts/libraries/league-src-v1.1-20261109/train"), Path("artifacts/models/v1.1/model.pt"), 243000000, Path("artifacts/runs/league-src-v1.1-20261109")),
    ("7357", Path("artifacts/libraries/league-src-7357-20261109/train"), Path("records/archive/models-2026-11-09/runs/nus-4159-economy-long-002/milestones/decisions-558819917/model.pt"), 244000000, Path("artifacts/runs/league-src-7357-20261109")),
    ("9786", Path("artifacts/libraries/league-src-9786-20261109/train"), Path("records/archive/models-2026-11-09/runs/p50-7357-long-001/milestones/decisions-798873732/model.pt"), 245000000, Path("artifacts/runs/league-src-9786-20261109")),
    ("10004", Path("artifacts/libraries/league-src-10004-20261109/train"), Path("records/archive/models-2026-11-09/runs/p50-7357-long-001/last-committed/step_010004/model.pt"), 246000000, Path("artifacts/runs/league-src-10004-20261109")),
]

WEIGHTS = (
    (1, 8, (0.60, 0.15, 0.15, 0.10)),
    (9, 12, (0.50, 0.20, 0.15, 0.15)),
    (13, 99, (0.40, 0.20, 0.20, 0.20)),
)
TRAIN_GAMES = 512
DEV_GAMES = 128
TEST_GAMES = 128
MAX_FRAMES_PER_TURN = 512


def weights_for(turn: int) -> tuple[float, ...]:
    for lo, hi, w in WEIGHTS:
        if lo <= turn <= hi:
            return w
    return WEIGHTS[-1][2]


def load_source(name: str, root: Path, seed_start: int) -> Dict[str, List[Dict[str, Any]]]:
    pools: Dict[str, List[Dict[str, Any]]] = {"train": [], "dev": [], "test": []}
    for path in sorted(root.glob("snap_*.json.gz")):
        with gzip.open(path, "rt", encoding="utf-8") as stream:
            record = json.load(stream)
        meta = record.get("meta") or {}
        seed = int(meta.get("seed", 0))
        offset = seed - seed_start
        if 0 <= offset < TRAIN_GAMES:
            split = "train"
        elif TRAIN_GAMES <= offset < TRAIN_GAMES + DEV_GAMES:
            split = "dev"
        elif TRAIN_GAMES + DEV_GAMES <= offset < TRAIN_GAMES + DEV_GAMES + TEST_GAMES:
            split = "test"
        else:
            continue
        for frame in record.get("frames") or []:
            fr = dict(frame)
            fr["source"] = name
            fr["seat"] = 0
            fr["source_game_seed"] = seed
            pools[split].append(fr)
    return pools


def pick_weighted(frames: List[Dict[str, Any]], rng: random.Random) -> List[Dict[str, Any]]:
    by_turn: Dict[int, Dict[str, List[Dict[str, Any]]]] = defaultdict(lambda: defaultdict(list))
    for fr in frames:
        by_turn[int(fr["turn"])][str(fr["source"])].append(fr)
    out: List[Dict[str, Any]] = []
    for turn in sorted(by_turn):
        available = by_turn[turn]
        source_names = [x[0] for x in SOURCES if x[0] in available]
        total_available = sum(len(available[s]) for s in source_names)
        target = min(MAX_FRAMES_PER_TURN, total_available)
        wmap = {s: w for s, w in zip([x[0] for x in SOURCES], weights_for(turn))}
        quotas = {s: int(round(target * wmap[s])) for s in source_names}
        # Normalize rounding and deficits; never fabricate frames.
        selected: List[Dict[str, Any]] = []
        for s in source_names:
            q = min(quotas[s], len(available[s]))
            if q <= 0:
                continue
            selected.extend(rng.sample(available[s], q))
        if len(selected) < target:
            used = {(x["source"], int(x["source_game_seed"]), int(x["turn"])) for x in selected}
            rest = [x for s in source_names for x in available[s]
                    if (x["source"], int(x["source_game_seed"]), int(x["turn"])) not in used]
            rng.shuffle(rest)
            selected.extend(rest[:target - len(selected)])
        out.extend(selected)
    return out


def validate_library(out: Path, expected_frames: Dict[str, int]) -> Dict[str, Any]:
    import hsbg_engine as E
    from hsbg.az.train.evaluate import EvalConfig, evaluate_policy
    from hsbg.az.train.policies import EngineBotPolicy
    from workflows.mirror_hard_gates import _drive_to_turn

    audits = {}
    for split in ("train", "dev", "test"):
        pool = MirrorSnapshotPool(str(out / split), sample="random")
        if pool.bad_files:
            raise RuntimeError(f"{split}: bad_files={pool.bad_files}")
        if pool.frames != expected_frames[split]:
            raise RuntimeError(f"{split}: frames {pool.frames} != expected {expected_frames[split]}")
        template = _drive_to_turn(E.Game(seed=730000), 1).state_json()
        checked = 0
        for frames in pool.index.values():
            for fr in frames:
                game = E.Game.from_json(template)
                result = game.apply_turn_snapshots([[0, json.dumps(fr.player, ensure_ascii=False)]], False)
                if (result.get("applied") != 1 or result.get("rejected")
                        or not result.get("pool_balance_ok") or not result.get("pool_species_ok")
                        or game.invariant_violations()):
                    raise RuntimeError(f"{split}: injection failed seed={fr.source_game_seed} turn={fr.turn} {result}")
                checked += 1
        strict = evaluate_policy(EngineBotPolicy(), EvalConfig(
            games=8, seed=990000 + {"train": 0, "dev": 1, "test": 2}[split],
            mirror_pool=pool, mirror_strict=True, collect_exposure=True))
        ms = strict["mirror"]
        if (strict["illegal_actions"] or strict["truncated_games"] or strict["truncated_combats"]
                or any(ms[k] for k in ("mirror_errors", "mirror_missing", "mirror_rejected",
                                       "mirror_fallback", "mirror_pool_unbalanced",
                                       "mirror_pool_species_unbalanced"))
                or ms["mirror_attempt"] != ms["mirror_applied"]):
            raise RuntimeError(f"{split}: strict audit failed {ms}")
        audits[split] = {"pool": pool.stats(), "checked": checked,
                         "strict": {"mirror": ms, "illegal_actions": strict["illegal_actions"],
                                    "truncated_games": strict["truncated_games"],
                                    "truncated_combats": strict["truncated_combats"]}}
    return audits


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--seed", type=int, default=20261110)
    a = ap.parse_args()
    out = a.out.resolve()
    if out.exists() and any(out.iterdir()):
        raise ValueError(f"output must be empty: {out}")
    for split in ("train", "dev", "test"):
        (out / split).mkdir(parents=True, exist_ok=False)
    source_pools: Dict[str, Dict[str, List[Dict[str, Any]]]] = {}
    source_meta = []
    for name, lib, model, seed_start, run in SOURCES:
        if not lib.is_dir():
            raise FileNotFoundError(f"source library missing: {name} {lib}")
        pools = load_source(name, lib, seed_start)
        source_pools[name] = pools
        rep_path = run / "report" / "report.json"
        rep = json.loads(rep_path.read_text(encoding="utf-8")) if rep_path.exists() else {}
        ra = rep.get("rule_audit") or {}
        if ra.get("cancel_actions") != 0 or ra.get("max_moves_per_turn", 99) > 5 or ra.get("move_violations") != 0:
            raise RuntimeError(f"source action rules failed: {name} {ra}")
        source_meta.append({
            "id": name, "library": str(lib), "report": str(rep_path), "model": str(model),
            "model_sha256": sha256(model), "seed_start": seed_start,
            "frames": {k: len(v) for k, v in pools.items()},
            "rule_audit": ra,
        })
    rng = random.Random(a.seed)
    train = []
    for name, _, _, _, _ in SOURCES:
        train.extend(source_pools[name]["train"])
    train = pick_weighted(train, rng)
    dev = [fr for name, _, _, _, _ in SOURCES for fr in source_pools[name]["dev"]]
    test = [fr for name, _, _, _, _ in SOURCES for fr in source_pools[name]["test"]]
    for split, frames in (("train", train), ("dev", dev), ("test", test)):
        if not frames:
            raise RuntimeError(f"empty split {split}")
        write_snapshot_file(str(out / split / "snap_league.json.gz"), frames,
                            seed=a.seed, learner_seat=0, engine=engine_stamp(),
                            meta={"driver": "model_eot_league", "sources": [x[0] for x in SOURCES],
                                  "weighting": "turn/source weighted; raw EOT; no calibration"})
    expected = {"train": len(train), "dev": len(dev), "test": len(test)}
    audits = validate_library(out, expected)
    manifests = {}
    model_meta = {x["id"]: x for x in source_meta}
    for split in ("train", "dev", "test"):
        manifest = {
            "schema": "hsrl.library/v1", "split": split, "driver": "model_eot_league",
            "digest": library_digest(out / split), "fingerprint": fingerprint(),
            "sources": source_meta, "games": {"train": 512 * 4, "dev": 128 * 4, "test": 128 * 4}[split],
            "frames": expected[split], "last_turn": int(max(int(fr["turn"]) for fr in
                (train if split == "train" else dev if split == "dev" else test))),
            "calibration": "none", "raw_eot": True,
            "validation": {"checked": audits[split]["checked"],
                           "accepted": audits[split]["checked"], "quarantined": 0},
            "strict_audit": audits[split]["strict"],
        }
        manifests[split] = manifest
        write_json(out / split / "manifest.json", manifest)
    root = {"schema": "hsrl.library/v1", "driver": "model_eot_league",
            "splits": manifests, "sources": source_meta,
            "weighting": "T1-8 60/15/15/10; T9-12 50/20/15/15; T13+ 40/20/20/20",
            "raw_eot": True, "calibration": "none", "seed": a.seed}
    write_json(out / "manifest.json", root)
    write_json(out / "validation.json", {"splits": expected, "audits": audits, "source_rule_audit": source_meta})
    print(json.dumps({"out": str(out), "frames": expected,
                      "digest": {k: manifests[k]["digest"] for k in manifests},
                      "sources": source_meta}, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
