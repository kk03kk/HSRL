PAD = "BGS_004"  # no passive growth when no Demon is played
FILLERS = ("BG26_135","BG23_002","BG24_009","BG25_004","BG26_528","BG26_OG_248","BG25_034")
RAT, RIDER, DAY = "BG31_326", "BG31_323", "BG31_893"
AZ, SURF, BRANN, KELP, BAL = "BG28_707","BG35_881","BG_LOE_077","BG36_701","BG35_883"
WILD, ABSORB, COIN = "BGS_126","BG35_911","BG28_810"
HOPE, POET, BROOD, WARD, NAD = "BG36_364","BG29_813","BG36_849","BGS_034","BGS_040"
