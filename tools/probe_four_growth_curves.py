CASES = ("mech","mech_double","mech_boxers","dragon","dragon_poet","pig","pig_primed","pig_fed",
         "pig_no_rider","elem","elem_fed","elem_more_absorb","elem_no_cash","elem_real_shops",
         "elem_no_double","elem_no_azerite","elem_no_brann","elem_budget","elem_budget_lean")


def board(case):
    if case=="quill_lone_source":
        return [RAT,"BG20_100"]
    if case in ("quill_ready","quill_offer","quill_cold_ready","quill_cold_search"):
        return [RIDER if case in ("quill_ready","quill_cold_ready") else "BG20_100",RAT,"BG36_331","BG33_885"]
    if case=="elem_offer":
        return [WILD,SURF,KELP,BRANN,BAL,PAD]
    if case.startswith("mech"):
        if case=="mech_boxers":
            return [ROBOT,DRONE,DRK,"BG26_149","BG26_149"]
        return [ROBOT,DRONE,DRK if case=="mech_double" else PAD]
    if case.startswith("dragon"):
        return [BROOD,POET if case=="dragon_poet" else PAD,HOPE,WARD,NAD,WARD]
    if case.startswith("pig"):
        # A battlecry-only boar on the starting board keeps four recipients
        # without introducing a second source of hand cards.
        return ["BG34_683" if case=="pig_no_rider" else RIDER,RAT,"BG20_100","BG31_320"]
    return [WILD,SURF,KELP,BRANN if case not in ("elem_no_brann","elem_budget_lean") else PAD,
            BAL if case not in ("elem_no_double","elem_budget_lean") else PAD,AZ if case!="elem_no_azerite" else PAD]


def make(seed,case):
    game=E.Game(seed=seed,config_json=json.dumps({"lobby_types":["DRAGON","MECHANICAL","QUILBOAR","ELEMENTAL","NAGA"]}))
    initial=json.loads(game.state_json())
    _drive_to_turn(game,1)
    state=json.loads(game.state_json())
    state["turn"]=9
    state["deity"]=state["paradox"]=None
    state["cfg"]["greater_trinket_turn"]=90
    state["cfg"]["lesser_trinket_turn"]=80
    for p in state["players"]:
        pristine=initial["players"][p["id"]]
        for k in ("counters","scheduled","stats","secrets","rewards","quests","levels","owed"):
            p[k]=pristine[k]
        p.update(hero=None,powers=[],pending=[],trinkets=[],effects=[],board=[],hand=[],
                 deity=None,hand_queue=[],health=1000,armor=0,tier=6,gold=10)
    if case in ("pig_primed","pig_fed","pig_no_rider","quill_ready","quill_offer"):
        state["players"][0]["stats"].update(gem_atk=6,gem_hp=3)
    g=E.Game.from_json(json.dumps(state))
    for seat in range(8):
        team=board(case) if seat==0 else []
        for card in team+list(FILLERS[:7-len(team)]):
            size=25 if seat==0 else 150
            debug(g,"add_minion",seat,zone="board",card=card,atk=size,hp=size)
    assert sum(m["atk"]+m["hp"] for m in own(g)["board"])==350
    debug(g,"refresh_shop")
    if case in ("quill_offer","elem_offer"):
        debug(g,"remove",zone="shop",index=0)
        debug(g,"add_minion",zone="shop",card=RIDER if case=="quill_offer" else AZ)
    return g


def step(g,a,seat=0):
    if not g.legal_mask(seat)[a]:
        raise ValueError((g.turn,a,own(g,seat)["pending"]))
    g.step(seat,a)


def hand_slot(g,card):
    return next((i for i,h in enumerate(own(g)["hand"]) if item_card(h)==card_ids()[card]),None)


def target(g,eid):
    options=own(g)["pending"][-1]["Target"]["options"]
    step(g,30+options.index(eid))


def cast(g,card,dst=None):
    index=hand_slot(g,card)
    step(g,46+8*index)
    if card==DAY:
        stats=own(g)["stats"]
        step(g,30 if stats["gem_atk"]<stats["gem_hp"] else 31)
    elif dst is not None:
        target(g,dst)


def supply(g,card,n):
    for _ in range(n):
        debug(g,"add_spell",zone="hand",card=card)


def operate(g,case):
    p=own(g)
    counts=Counter()
    if case.startswith("pig"):
        if case in ("pig_fed","pig_no_rider"):
            supply(g,DAY,2)
        while hand_slot(g,DAY) is not None:
            cast(g,DAY)
            counts["choices"]+=1
    if case.startswith("mech"):
        # Empty copies generated by the robot onto itself, preserving its stack.
        while own(g)["hand"] and g.legal_mask(0)[126]:
            step(g,126)
            counts["manual_magnets"]+=1
    if case.startswith("elem"):
        budget=case in ("elem_budget","elem_budget_lean")
        if case!="elem_real_shops" and not budget:
            debug(g,"clear_zone",zone="shop")
            debug(g,"add_minion",zone="shop",card=WILD,atk=20+p["stats"]["tavern_elemental_atk"],
                  hp=20+p["stats"]["tavern_elemental_hp"])
        if case!="elem" and not budget:
            for _ in range(6):
                supply(g,COIN,1)
                cast(g,COIN)
                counts["coins"]+=1
        step(g,23+2)
        target(g,p["board"][1]["eid"])
        if budget:
            # A real paid refresh, at most three times, only while no Elemental is offered.
            for _ in range(3):
                shop=own(g)["shop"]
                if any(slot["item"].get("Minion",{}).get("races",0)&8 for slot in shop):
                    break
                if not g.legal_mask(0)[1]:
                    break
                step(g,1)
                counts["paid_rolls"]+=1
        counts["native_absorbs"]=sum(item_card(h)==card_ids()[ABSORB] for h in own(g)["hand"])
        if case=="elem_more_absorb":
            supply(g,ABSORB,4)
        while hand_slot(g,ABSORB) is not None:
            if case=="elem_no_cash":
                # Remove the foregone spells, preventing hand congestion in this ablation.
                debug(g,"remove",zone="hand",index=hand_slot(g,ABSORB))
            else:
                cast(g,ABSORB,p["board"][0]["eid"])
                counts["absorption_plays"]+=1
    return counts


def measure(seed,case,last_turn=15):
    g=make(seed,case)
    rows=[]
    for turn in range(9,last_turn+1):
        assert g.turn==turn and not g.is_over()
        c=operate(g,case)
        step(g,0)
        p=own(g)
        assert p["ended_turn"] and g.turn==turn and len(p["board"])==7
        stats=p["stats"]
        rows.append(dict(t=turn,strength=sum(m["atk"]+m["hp"] for m in p["board"]),
                         shop_buff=stats["tavern_elemental_atk"],gem_size=2+stats["gem_atk"]+stats["gem_hp"],
                         hope_counter=sum(m["counter"] for m in p["board"] if m["card"]==card_ids()[HOPE]),
                         **c))
        for seat in range(1,8):
            step(g,0,seat)
        assert g.truncated_combats==0
    return rows


def check_shop_observation(seed):
    base=make(seed,"elem_budget")
    debug(base,"clear_zone",zone="shop")
    debug(base,"add_minion",zone="shop",card=PAD,atk=20,hp=20)
    alternate=json.loads(base.state_json())
    alternate["players"][0]["stats"].update(tavern_elemental_atk=60,tavern_elemental_hp=60)
    boosted=E.Game.from_json(json.dumps(alternate))
    same=all(bytes(a)==bytes(b) for a,b in zip(base.observe(0),boosted.observe(0)))
    assert same and bytes(base.legal_mask(0))==bytes(boosted.legal_mask(0))
    for g in (base,boosted):
        step(g,1)
    def minions(g):
        return [s["item"]["Minion"] for s in own(g)["shop"] if "Minion" in s["item"]]
    one,two=minions(base),minions(boosted)
    assert [m["card"] for m in one]==[m["card"] for m in two]
    return dict(same_input=same,max_stat_delta=max((b["hp"]-a["hp"] for a,b in zip(one,two)),default=0))


